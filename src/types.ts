import type { Feature, FeatureCollection, Geometry } from 'geojson';

export const FEATURE_TYPES = ['battle', 'city', 'route', 'boundary', 'uprising', 'economic', 'political'] as const;
export type FeatureType = (typeof FEATURE_TYPES)[number];

export const CONFIDENCE_LEVELS = ['precise', 'approximate', 'schematic'] as const;
export type Confidence = (typeof CONFIDENCE_LEVELS)[number];

export interface Source {
  citation: string;
  url?: string;
}

/** Properties of a historical feature as authored in data/eras/*.geojson. */
export interface HistoricalProps {
  id: string;
  era: string;
  title: string;
  label?: string;
  /** ISO-style partial date: "1519", "1519-11" or "1519-11-08". Use start/end for spans. */
  date?: string;
  start?: string;
  end?: string;
  type: FeatureType;
  description: string;
  confidence: Confidence;
  note?: string;
  sources: (Source | string)[];
  /** Modern place name used by scripts/check-places.mjs to verify coordinates. */
  modern_place?: string;
  /** Clip polygon to the modern coastline at load time. */
  clip?: 'land';
  /** Ids of other polygons to cut out of this one at load time. */
  exclude?: string[];
  /** Routes are directional unless set to false. */
  directional?: boolean;
  /** Geometry generated by scripts/derive-boundaries.mjs. */
  derived?: boolean;
  from_states?: string[];
  style?: { color?: string; fill?: 'water' };
}

export type HistoricalFeature = Feature<Geometry, HistoricalProps>;
export type HistoricalCollection = FeatureCollection<Geometry, HistoricalProps> & { name?: string };

export interface Era {
  id: string;
  title: string;
  start: number;
  end: number;
  /** File in data/eras/, or null while the era is still being prepared. */
  file: string | null;
  bbox: [number, number, number, number];
  summary?: string;
  /** Chapters of the companion book to read alongside the era, e.g. "chs. 1–3". */
  reading?: string;
}
